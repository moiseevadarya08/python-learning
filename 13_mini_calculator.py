num1 = int(input("Введите число 1:"))
num2 = int(input("Введите число 2:"))
operation = input("Введите операцию (+, -, *, /)")
if operation == "+":
    print(num1 + num2)
if operation == "-":
    print(num2 - num1)
if operation == "*":
    print(num1 * num2)
if operation == "/":
    print(num1 / num2)
