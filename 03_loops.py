# Задача 1: Вывести числа из списка
numbers = [1, 2, 3, 4]
for i in numbers:
    print(i)

# Задача 2: Посчитать сумму чисел
numbers = [1, 2, 3, 4]
total = 0
for i in numbers:
    total += i
print(total)

# Задача 3: Найти чётные числа
numbers = [2, 5, 8, 11]
for i in numbers:
    if i % 2 == 0:
        print(i)
